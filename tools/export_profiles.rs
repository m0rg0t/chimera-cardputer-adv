// Compiled as a CHIMERA example by regenerate-profiles.sh.
use chimera::anatomy::geom::Vec2;
use chimera::anatomy::human::{BODY_MALE, BodyMix, NEUTRAL};
use chimera::phonetics::inventory::{Manner, Voicing, phoneme};
use chimera::phonetics::planner::{diphthong_parts, vowel_artic};
use chimera::voice::human_airway::HumanAirway;
use chimera::voice::human_voice::HumanVoice;
use std::time::Instant;

const RATE: usize = 24_000;
const SECTIONS: usize = 12;
const VELUM: usize = 6;
const PULSE_STEPS: usize = 128;
const SHAPES: [usize; 10] = [26, 13, 18, 12, 8, 8, 6, 6, 10, 14];

fn point(x: f64, y: f64) -> Vec2 {
    Vec2 { x, y }
}

fn area_at(areas: &[f64], fraction: f64) -> f64 {
    let position = (fraction * areas.len() as f64 - 0.5).clamp(0.0, (areas.len() - 1) as f64);
    let first = position as usize;
    let next = (first + 1).min(areas.len() - 1);
    areas[first] + (areas[next] - areas[first]) * (position - first as f64)
}

fn emit_outline(points: &[Vec2], count: usize) {
    let mut distances = vec![0.0];
    for edge in points.windows(2) {
        let delta = (edge[1].x - edge[0].x).hypot(edge[1].y - edge[0].y);
        distances.push(distances.last().unwrap() + delta);
    }
    for i in 0..count {
        let target = distances.last().unwrap() * i as f64 / (count - 1) as f64;
        let edge = distances.partition_point(|d| *d <= target).clamp(1, points.len() - 1);
        let span = distances[edge] - distances[edge - 1];
        let t = if span > 0.0 { (target - distances[edge - 1]) / span } else { 0.0 };
        let a = points[edge - 1];
        let b = points[edge];
        let x = a.x + t * (b.x - a.x);
        let y = a.y + t * (b.y - a.y);
        print!("{{{}, {}}}, ", ((x + 9.5) * 4.15).round(), ((23.5 - y) * 4.15).round());
    }
}

fn main() {
    let mut args = std::env::args().skip(1);
    let file = std::fs::read_to_string(args.next().expect("phones.tsv path")).unwrap();
    let phones: Vec<_> = file.lines().map(|line| line.split_once('\t').unwrap()).collect();
    let mut airway = HumanAirway::new(96_000.0, BODY_MALE);
    let voice = HumanVoice::with_defaults(48_000.0);
    let glottis = voice.glottis.params;

    println!("// Generated by tools/regenerate-profiles.sh.\n#pragma once");
    println!("#include <cstddef>\n#include <cstdint>\n\nnamespace chimera_adv {{");
    println!("constexpr unsigned kSampleRate = {RATE};");
    println!("constexpr std::size_t kSections = {SECTIONS};");
    println!("constexpr std::size_t kVelum = {VELUM};");
    println!("constexpr std::size_t kVowelCount = 5;");
    println!("constexpr std::size_t kPulseSteps = {PULSE_STEPS};");
    println!("enum Phone : uint8_t {{");
    for (name, _) in &phones { println!("    Ph{name},"); }
    println!("    PhCount\n}};");
    println!("enum class Manner : uint8_t {{ Pause, Vowel, Glide, Nasal, Stop, Fricative, Affricate, Breath }};");
    println!("struct Point {{ uint8_t x, y; }};");
    println!("constexpr unsigned kOutlineLengths[] = {{{}}};", SHAPES.iter().map(usize::to_string).collect::<Vec<_>>().join(", "));
    println!("constexpr unsigned kPointCount = {};", SHAPES.iter().sum::<usize>());
    println!("struct Profile {{\n    const char* ipa;\n    Manner manner;\n    bool voiced;");
    println!("    uint16_t ms;\n    uint8_t jet;\n    float reflection[kSections - 1];\n    float velum[3];\n    Point head[kPointCount];\n}};");
    println!("constexpr Profile kProfiles[PhCount] = {{");
    for (_, ipa) in &phones {
        let def = phoneme(ipa, BodyMix::MALE);
        let first = diphthong_parts(ipa).map_or(*ipa, |(first, _)| first);
        let mut artic = if let Some(p) = vowel_artic(first, BodyMix::MALE) {
            p.apply_to(&NEUTRAL)
        } else if let Some(d) = def {
            d.targets.apply_to(&NEUTRAL)
        } else {
            assert_eq!(*ipa, "_", "missing /{ipa}/");
            NEUTRAL
        };
        if def.is_some_and(|d| d.manner == Manner::Nasal) { artic.velum = 0.8; }
        let (kind, voiced, duration) = if *ipa == "_" {
            ("Pause", false, 0.08)
        } else if vowel_artic(first, BodyMix::MALE).is_some() {
            ("Vowel", true, if first == *ipa { 0.105 } else { 0.16 })
        } else {
            let d = def.unwrap();
            let kind = match d.manner {
                Manner::Stop | Manner::Tap => "Stop",
                Manner::Nasal => "Nasal",
                Manner::Affricate => "Affricate",
                Manner::Fricative => "Fricative",
                Manner::Glottal => "Breath",
                _ => "Glide",
            };
            (kind, d.voicing == Voicing::Voiced, d.dur)
        };
        airway.apply(&artic, 0.0);
        let f = airway.frame.as_ref().unwrap();
        let areas: [f64; SECTIONS] = std::array::from_fn(|section| {
            let (index, count, source) = if section < VELUM {
                (section, VELUM, &airway.ph_areas)
            } else {
                (section - VELUM, SECTIONS - VELUM, &airway.or_areas)
            };
            let inverse: f64 = (0..16).map(|sub| {
                let x = (index as f64 + (sub as f64 + 0.5) / 16.0) / count as f64;
                1.0 / area_at(source, x).max(0.018)
            }).sum();
            16.0 / inverse
        });
        let jet = if kind == "Breath" { 0 } else {
            (VELUM..SECTIONS).min_by(|a, b| areas[*a].total_cmp(&areas[*b])).unwrap() + 1
        };
        print!("    {{\"{ipa}\", Manner::{kind}, {voiced}, {}, {jet}, {{ ", (duration * 1000.0) as u16);
        for pair in areas.windows(2) {
            print!("{:.7}f, ", (pair[0] - pair[1]) / (pair[0] + pair[1]));
        }
        let (l, r, n) = (areas[VELUM - 1], areas[VELUM], f.velum_port.max(0.0));
        let sum = l + r + n;
        print!("}}, {{ {:.7}f, {:.7}f, {:.7}f }},\n        {{ ", (l/sum).sqrt(), (r/sum).sqrt(), (n/sum).sqrt());
        // The adult male silhouette's nose and skull landmarks follow src/ui/render/profile.ts.
        let mut skin = f.upper_lip.iter().skip(7).copied().collect::<Vec<_>>();
        skin.extend([
            point(7.05, 10.6), point(7.75, 10.78), point(8.75, 11.05), point(9.25, 11.65),
            point(8.95, 12.6), point(8.35, 13.9), point(7.7, 15.0), point(7.95, 16.1),
            point(7.9, 18.1), point(6.9, 20.5), point(3.0, 22.9), point(-2.2, 22.7),
            point(-6.9, 19.6), point(-8.7, 15.4), point(-8.3, 11.9), point(-7.4, 8.9),
            point(-6.8, 4.8), point(-6.6, 0.0), point(-6.6, -4.6),
        ]);
        let mut chin = f.lower_lip.iter().skip(7).copied().collect::<Vec<_>>();
        chin.extend([point(7.75, 4.6-artic.jaw), point(6.9, 3.4-artic.jaw),
            point(5.0, 3.0-artic.jaw), point(3.0, 1.7), point(2.38, -1.5), point(2.3, -4.6)]);
        let paths: [&[Vec2]; 10] = [&skin, &chin, &f.tongue, &f.outer, &f.upper_lip, &f.lower_lip,
            &f.upper_teeth, &f.lower_teeth, &f.velum, &f.nasal_cavity];
        for (path, count) in paths.into_iter().zip(SHAPES) { emit_outline(path, count); }
        println!("}} }},");
    }
    println!("}};\n\nconstexpr float kGlottalPulse[kPulseSteps + 1] = {{");
    let open = glottis.open_quotient - 0.18 * (glottis.effort - 0.5);
    let skew = glottis.skew;
    let sharp = glottis.closure_sharpness;
    let pi = std::f64::consts::PI;
    for i in 0..=PULSE_STEPS {
        let t = (i as f64 / PULSE_STEPS as f64) / open;
        let pulse = if t >= 1.0 { 0.0 } else if t < skew {
            0.5 - 0.5 * (pi * t / skew).cos()
        } else {
            let u = (t - skew) / (1.0 - skew);
            let soft = 0.5 + 0.5 * (pi * u).cos();
            soft + ((0.5 * pi * u).cos() - soft) * sharp
        };
        if i % 8 == 0 { print!("    "); }
        print!("{pulse:.7}f,");
        if i % 8 == 7 || i == PULSE_STEPS { println!(); } else { print!(" "); }
    }
    println!("}};\n}}  // namespace chimera_adv");

    if args.any(|arg| arg == "--bench") {
        for (rate, os) in [(48_000, 2), (48_000, 1), (RATE, 1)] {
            let mut voice = HumanVoice::new(rate as f64, BODY_MALE, os);
            voice.set_articulation(&vowel_artic("a", BodyMix::MALE).unwrap(), None);
            voice.set_gate(1.0);
            let mut block = [0.0; 128];
            let start = Instant::now();
            for _ in 0..4 * rate / block.len() { voice.render(std::hint::black_box(&mut block)); }
            let net = &voice.airway.net;
            eprintln!("{rate} Hz {os}x: {} nodes, {} branches, {:.1}% desktop core", net.n_nodes,
                net.n_branches, 25.0 * start.elapsed().as_secs_f64());
        }
    }
}
